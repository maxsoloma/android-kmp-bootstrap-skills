package bootstrap

import kotlinx.serialization.json.*
import java.nio.file.Files
import java.nio.file.LinkOption.NOFOLLOW_LINKS
import java.nio.file.Path
import java.security.MessageDigest
import kotlin.io.path.readText

fun sha256(bytes: ByteArray): String = MessageDigest.getInstance("SHA-256").digest(bytes).joinToString("") { "%02x".format(it) }
private fun canonical(v: JsonElement): JsonElement = when (v) {
    is JsonObject -> JsonObject(v.toSortedMap().mapValues { canonical(it.value) })
    is JsonArray -> JsonArray(v.map(::canonical))
    else -> v
}
private fun treeHash(files: Map<String, ByteArray>): String {
    val digest = MessageDigest.getInstance("SHA-256")
    files.toSortedMap().forEach { (name, bytes) ->
        digest.update(name.toByteArray(Charsets.UTF_8)); digest.update(0.toByte())
        digest.update(sha256(bytes).toByteArray(Charsets.UTF_8)); digest.update(0.toByte())
    }
    return digest.digest().joinToString("") { "%02x".format(it) }
}
private val recipeHash by lazy { treeHash(Resources.paths.associateWith { Resources.bytes(it) }) }
fun readObject(path: Path): JsonObject = Json.parseToJsonElement(path.readText()) as? JsonObject
    ?: throw IllegalArgumentException("Expected a JSON object in $path")

/** The plan retains generated bytes, so review and publication use the same render. */
data class GenerationPlan(val options: Options, val spec: JsonObject, val lock: JsonObject, val rendered: Rendered) {
    fun document(): JsonObject {
        val o = options
        val commands = rendered.metadata.getValue("checks").jsonObject.flatMap { (target, checks) ->
            checks.jsonArray.map { check -> mapOf("target" to target, "command" to "./kotlin " + check.jsonArray.joinToString(" ") { it.jsonPrimitive.content }, "requires" to if (target == "ios") "macOS + Xcode and iOS simulator runtime" else "Toolchain-provisioned dependencies and platform tools") }
        } + if (o.ui == "swiftui") listOf("build", "test").map { check -> mapOf("target" to "shared-logic", "command" to "./kotlin $check --platform jvm", "requires" to "Toolchain-provisioned JVM tools; no Xcode required") } else emptyList()
        return value(mapOf(
            "valid" to true, "missing_fields" to emptyList<String>(), "issues" to emptyList<String>(),
            "output" to o.output.toString(), "spec" to spec, "lock" to lock,
            "build_system" to "kotlin-toolchain",
            "stack" to mapOf("ui" to o.ui, "di" to o.di, "navigation" to o.navigation,
                "firebase" to firebaseStatus(o),
                "network" to o.network, "storage" to o.storage, "network_url" to o.networkUrl,
                "network_adapters" to if (o.network == "ktor") networkAdapters(o.targets) else emptyMap<String, String>(),
                "storage_adapters" to if (o.storage == "settings") storageAdapters(o.targets) else emptyMap<String, String>(),
                "pins" to selectedPins(o)),
            "files" to rendered.files.keys.sorted(),
            "modules" to rendered.files.keys.filter { it.endsWith("/module.yaml") }.map { it.substringBefore('/') }.sorted(),
            "toolchain" to mapOf("pins" to toolchain, "modules" to rendered.files.filterKeys { it.endsWith("module.yaml") }.mapValues { it.value.toString(Charsets.UTF_8) }),
            "requirements" to listOf("Java 17+ runs this generator; Kotlin wrapper provisions its build tools on first build", "macOS + full Xcode for iOS; simulator runtime for native tests", "Network for initial dependency/tool downloads; generation stays offline"),
            "verification" to mapOf("status" to "NOT_RUN", "runner" to "bootstrap verify OUTPUT", "commands" to commands,
                "scope" to "Actual Toolchain compilation and platform unit/browser tests. Device UI, app-store signing and live endpoint behavior require separate checks."),
        )).jsonObject
    }

}
data class PlanningResult(val plan: GenerationPlan?, val issues: List<Issue>) {
    val valid get() = plan != null && issues.isEmpty()
    fun document(): JsonObject = plan?.document() ?: value(Resolution(null, null, issues).failure()).jsonObject
}
fun planProject(spec: JsonObject, output: Path, suppliedLock: JsonObject? = null): PlanningResult {
    val resolved = resolveSpec(spec, output)
    if (!resolved.valid) return PlanningResult(null, resolved.issues)
    return try {
        val o = resolved.options!!
        val rendered = renderModern(o).also { configureFirebase(o, it.files) }
        val lock = value(mapOf("schema_version" to 1, "generator_version" to CLI_VERSION,
            "spec_sha256" to sha256(canonical(resolved.spec!!).toString().toByteArray(Charsets.UTF_8)),
            "recipes_sha256" to recipeHash, "files_sha256" to treeHash(rendered.files))).jsonObject
        if (suppliedLock != null && suppliedLock != lock) return PlanningResult(null, listOf(Issue("lock", "lock_mismatch", "Lock does not match the configuration, generator or bundled recipes. Use the matching CLI/spec, or explicitly create a new recipe without the old lock.")))
        check("bootstrap.spec.json" !in rendered.files && "bootstrap.lock.json" !in rendered.files) { "Generated recipe conflicts with reserved config files" }
        rendered.files["bootstrap.spec.json"] = encode(resolved.spec).toByteArray(Charsets.UTF_8)
        rendered.files["bootstrap.lock.json"] = encode(lock).toByteArray(Charsets.UTF_8)
        PlanningResult(GenerationPlan(o, resolved.spec, lock, rendered), emptyList())
    } catch (e: Exception) {
        PlanningResult(null, listOf(Issue("configuration", "generation_error", e.message ?: "Cannot render recipe")))
    }
}
fun publishPlan(plan: GenerationPlan): JsonObject {
    publish(plan.options.output, plan.rendered.files)
    return value(mapOf("output" to plan.options.output.toString(), "files" to plan.rendered.files.size,
        "targets" to plan.options.targets, "build_status" to "NOT_RUN", "verification" to plan.document()["verification"])).jsonObject
}
fun configCommand(args: List<String>, generate: Boolean): Int {
    try {
        val a = Arguments(args, setOf("config", "output", "lock"), if (generate) setOf("dry-run") else emptySet())
        require(a.positional.isEmpty()) { "Config mode uses --output PATH; do not mix legacy positional arguments or options" }
        val config = Path.of(a.get("config")).toAbsolutePath().normalize()
        val output = Path.of(a.get("output")).toAbsolutePath().normalize()
        val lockPath = a.options["lock"]?.let { Path.of(it).toAbsolutePath().normalize() }
            ?: config.resolveSibling("bootstrap.lock.json").takeIf { Files.exists(it, NOFOLLOW_LINKS) }
        val result = planProject(readSpec(config), output, lockPath?.let(::readObject))
        if (!result.valid) { print(encode(result.document())); return 1 }
        print(encode(if (generate && "dry-run" !in a.options) publishPlan(result.plan!!) else result.document()))
        return 0
    } catch (e: Exception) {
        print(encode(mapOf("valid" to false, "missing_fields" to emptyList<String>(), "issues" to listOf(Issue("input", "invalid_input", e.message ?: "Invalid input").document()))))
        return 1
    }
}
